def main():
    """Fit all SPARC galaxies and post-process for multi-BH decompositions."""
    
    # Load master catalog
    master = pd.read_csv('../data/sparc_sample123.csv')
    galaxies = master['Galaxy'].values
    
    results = []
    
    for gal in galaxies:
        # Load rotation curve
        try:
            d = np.loadtxt(f'{DATA_DIR}/{gal}_rotmod.dat', comments='#')
            r_obs = d[:, 0]
            v_obs = d[:, 1]
            e_v = d[:, 2]
            v_gas = d[:, 3]
            v_disk = d[:, 4]
            v_bul = d[:, 5]
        except:
            continue
        
        # Get galaxy properties
        gal_row = master[master['Galaxy'] == gal].iloc[0]
        T = int(gal_row['T'])
        V_flat = gal_row['Vflat']
        n_pts = len(r_obs)
        
        # Estimate M_central (Kormendy & Ho 2013)
        log_MBH = 8.5 + 4.4 * np.log10(V_flat / np.sqrt(2) / 200.0)
        M_central_estimate = 10**log_MBH
        
        # Prepare for fitting
        Vbar2 = baryon_squared(v_gas, v_disk, v_bul)
        mask = v_obs**2 > Vbar2
        r = r_obs[mask]
        v = v_obs[mask]
        sig = np.maximum(e_v[mask], SIGMA_V_FLOOR)
        Vbar2_m = Vbar2[mask]
        
        if len(r) < 5:
            continue
        
        # Fit each n_shells from 0 to MAX_SHELLS
        bic_values = {}
        params_per_n = {}
        chi2_per_n = {}
        
        for n in range(MAX_SHELLS + 1):
            dof = len(r) - (2 + 3*n)
            if dof < 1:
                break
            
            p, chi2 = fit_configuration(r, v, sig, Vbar2_m, n)
            if p is None or not np.isfinite(chi2):
                bic_values[n] = np.nan
            else:
                bic = chi2 + (2 + 3*n) * np.log(len(r))
                bic_values[n] = bic
                params_per_n[n] = p
                chi2_per_n[n] = chi2
        
        # Select best n_shells by BIC
        valid_n = [n for n in bic_values if np.isfinite(bic_values[n])]
        if not valid_n:
            continue
        
        best_n = min(valid_n, key=lambda n: bic_values[n])
        best_params = params_per_n[best_n]
        best_chi2 = chi2_per_n[best_n]
        best_bic = bic_values[best_n]
        best_chi2_r = best_chi2 / (len(r) - (2 + 3*best_n))
        
        # Extract parameters
        rho0_burk = best_params[0]
        a_burk = best_params[1]
        
        # Record base info
        rec = {
            'Galaxy': gal,
            'T': T,
            'V_flat': V_flat,
            'n_pts': n_pts,
            'M_central_estimate': M_central_estimate,
            'fw_best_n_shells': best_n,
            'fw_best_bic': best_bic,
            'fw_best_chi2': best_chi2,
            'fw_best_chi2_red': best_chi2_r,
            'burk_rho0': rho0_burk,
            'burk_a_kpc': a_burk,
        }
        
        # Add shell info and multi-BH decomposition
        for i in range(best_n):
            base = 2 + 3*i
            M_sh = best_params[base]
            r_sh = best_params[base+1]
            sigma_frac = best_params[base+2]
            sigma_sh = sigma_frac * r_sh
            
            n_BH, M_BH_each, cr = decompose_shell_multi_BH(M_sh, M_central_estimate)
            
            rec[f'shell{i+1}_r_kpc'] = r_sh
            rec[f'shell{i+1}_M'] = M_sh
            rec[f'shell{i+1}_sigma_kpc'] = sigma_sh
            rec[f'shell{i+1}_M_BH_single'] = shell_to_implied_BH(M_sh)
            rec[f'shell{i+1}_decomp_n_BH'] = n_BH
            rec[f'shell{i+1}_decomp_M_BH_each'] = M_BH_each
            rec[f'shell{i+1}_decomp_central_ratio'] = cr
            rec[f'shell{i+1}_decomp_acceptable'] = (cr <= M_CENTRAL_FRACTION_LIMIT)
        
        results.append(rec)
        print(f"{gal}: n={best_n}, chi2_r={best_chi2_r:.2f}")
    
    # Write output
    df = pd.DataFrame(results)
    df.to_csv(OUTPUT_FILE, index=False)
    print(f"\nWrote {len(df)} galaxies to {OUTPUT_FILE}")

if __name__ == '__main__':
    main()